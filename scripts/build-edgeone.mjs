#!/usr/bin/env node
// Bundles the EdgeOne Pages Node Functions runtime.
//
//   node scripts/build-edgeone.mjs           # (re)build the bundle
//   node scripts/build-edgeone.mjs --check   # verify the committed bundle is current
//
// Why a bundle instead of TypeScript sources in node-functions/**:
//   - the deployed artifact is exactly what was tested locally;
//   - `cloudflare:workers` is resolved at build time (aliased to a stub), so the
//     platform bundler never sees a `cloudflare:` specifier it cannot resolve;
//   - mysql2 stays external (listed in package.json dependencies and in
//     edgeone.json → cloudFunctions.nodejs.externalNodeModules).
//
// The output is committed, the same way server/index.mjs is for the FC package.

import { build } from 'esbuild';
import { readFile, rm } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outFile = path.join(rootDir, 'node-functions', '_nodewarden', 'runtime.mjs');
const stubFile = path.join(rootDir, 'server', 'cf-workers-stub.mjs');

const normalizeEol = (text) => text.replace(/\r\n/g, '\n');

const banner = `// GENERATED by scripts/build-edgeone.mjs — do not edit.
// EdgeOne Pages Node Functions runtime for NodeWarden (BYO-DB edition).
// Rebuild after changing server/ or src/: npm run build:edgeone
`;

/** @param {string} outfile @param {import('esbuild').LogLevel} logLevel */
function bundle(outfile, logLevel = 'warning') {
  return build({
    entryPoints: [path.join(rootDir, 'server', 'edgeone.ts')],
    outfile,
    bundle: true,
    platform: 'node',
    format: 'esm',
    // EdgeOne Pages documents Node.js v20.x for Node Functions; targeting node20
    // keeps the output runnable on both v20 and v22.
    target: 'node20',
    external: ['mysql2'],
    alias: { 'cloudflare:workers': stubFile },
    legalComments: 'none',
    logLevel,
    banner: { js: banner },
  });
}

async function check() {
  const tmpFile = `${outFile}.check`;
  await rm(tmpFile, { force: true });
  try {
    const committed = await readFile(outFile, 'utf8').catch(() => null);
    if (committed === null) {
      console.error(`✗ ${path.relative(rootDir, outFile)} is missing — run: npm run build:edgeone`);
      return false;
    }
    await bundle(tmpFile, 'silent');
    const fresh = await readFile(tmpFile, 'utf8');
    // Compare with line endings normalized: on Windows `core.autocrlf=true`
    // rewrites the checked-out bundle to CRLF while esbuild always emits LF, so
    // a byte comparison reported "stale" on every fresh clone with no real diff.
    if (normalizeEol(committed) !== normalizeEol(fresh)) {
      console.error(`✗ ${path.relative(rootDir, outFile)} is stale — run: npm run build:edgeone`);
      return false;
    }
    console.log(`✓ ${path.relative(rootDir, outFile)} matches the sources`);
    return true;
  } finally {
    await rm(tmpFile, { force: true });
  }
}

if (process.argv.includes('--check')) {
  process.exit((await check()) ? 0 : 1);
}

await bundle(outFile);

const output = await readFile(outFile, 'utf8');
if (output.includes('cloudflare:')) {
  await rm(outFile, { force: true });
  console.error('✗ bundle still references cloudflare: — check the alias in this script');
  process.exit(1);
}
if (!output.includes('handleEdgeOneRequest')) {
  await rm(outFile, { force: true });
  console.error('✗ bundle does not export handleEdgeOneRequest');
  process.exit(1);
}

console.log(`✓ ${path.relative(rootDir, outFile)} (${(output.length / 1024 / 1024).toFixed(2)} MB)`);
